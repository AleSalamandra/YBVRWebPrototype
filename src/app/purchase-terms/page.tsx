function RichText({ text }: { text: string }) {
  const parts = text.split(
    /(\*\*[^*]+\*\*|https?:\/\/[^\s(),;]+|www\.[^\s(),;]+|[\w.+-]+@[\w.-]+\.[a-z]{2,})/gi
  );

  return (
    <>
      {parts.map((part, index) => {
        if (
          part.startsWith("**") &&
          part.endsWith("**")
        ) {
          return (
            <strong key={index}>
              {part.slice(2, -2)}
            </strong>
          );
        }

        if (/^(https?:\/\/|www\.)/i.test(part)) {
          const url = part.replace(/[.!?]+$/, "");

          const href = url.startsWith("www.")
            ? `https://${url}`
            : url;

          return (
            <span key={index}>
              <a href={href}>{url}</a>
              {part.slice(url.length)}
            </span>
          );
        }

        if (
          /^[\w.+-]+@[\w.-]+\.[a-z]{2,}$/i.test(part)
        ) {
          return (
            <a
              key={index}
              href={`mailto:${part}`}
            >
              {part}
            </a>
          );
        }

        return part;
      })}
    </>
  );
}

