function renderBlocks(text: string) {
  const blocks = text.trim().split(/\n\s*\n/).filter(Boolean);
  const result: ReactNode[] = [];

  for (let i = 0; i < blocks.length; i++) {
    const block = blocks[i];

    if (block.startsWith("- ")) {
      const key = i;
      const items: string[] = [];

      while (
        i < blocks.length &&
        blocks[i].startsWith("- ")
      ) {
        items.push(blocks[i].slice(2));
        i++;
      }

      i--;

      result.push(
        <ul key={key} className={styles.list}>
          {items.map((item, index) => (
            <li key={index}>
              <LinkedText text={item} />
            </li>
          ))}
        </ul>
      );
    } else if (
      block.startsWith("**") &&
      block.endsWith("**")
    ) {
      result.push(
        <h3 key={i} className={styles.subheading}>
          {block.slice(2, -2)}
        </h3>
      );
    } else if (block.startsWith("YBVR, Inc.\n")) {
      result.push(
        <address key={i} className={styles.address}>
          {block.split("\n").map((line, index) => (
            <div key={index}>{line}</div>
          ))}
        </address>
      );
    } else {
      result.push(
        <p key={i}>
          <LinkedText text={block} />
        </p>
      );
    }
  }

  return result;
}

